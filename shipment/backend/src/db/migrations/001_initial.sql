CREATE TABLE IF NOT EXISTS `agents` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `email` VARCHAR(150) NOT NULL,
  `phone` VARCHAR(30) NULL,
  `password_hash` VARCHAR(255) NOT NULL,
  `full_name` VARCHAR(160) NOT NULL,
  `avatar_url` VARCHAR(1000) NULL,
  `role` ENUM('ADMIN', 'SHIPPER') NOT NULL DEFAULT 'SHIPPER',
  `account_status` ENUM('ACTIVE', 'LOCKED') NOT NULL DEFAULT 'ACTIVE',
  `availability` ENUM('AVAILABLE', 'BUSY', 'OFFLINE') NOT NULL DEFAULT 'AVAILABLE',
  `service_areas` JSON NOT NULL,
  `rating` DECIMAL(3,2) NOT NULL DEFAULT 5.00,
  `completed_deliveries` INT UNSIGNED NOT NULL DEFAULT 0,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `agents_email_unique` (`email`),
  UNIQUE KEY `agents_phone_unique` (`phone`),
  KEY `agents_dispatch_idx` (`role`, `availability`, `account_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `shipments` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `tracking_number` VARCHAR(40) NOT NULL,
  `order_reference` VARCHAR(100) NOT NULL,
  `provider_code` VARCHAR(30) NOT NULL DEFAULT 'UTE_EXPRESS',
  `status` ENUM('PENDING_ASSIGNMENT', 'ASSIGNED', 'ACCEPTED', 'PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'DELIVERY_FAILED', 'RETURNED', 'CANCELLED') NOT NULL DEFAULT 'PENDING_ASSIGNMENT',
  `pickup_name` VARCHAR(160) NOT NULL,
  `pickup_phone` VARCHAR(30) NOT NULL,
  `pickup_address` VARCHAR(500) NOT NULL,
  `pickup_area` VARCHAR(120) NULL,
  `recipient_name` VARCHAR(160) NOT NULL,
  `recipient_phone` VARCHAR(30) NOT NULL,
  `recipient_address` VARCHAR(500) NOT NULL,
  `delivery_note` VARCHAR(1000) NULL,
  `payment_method` ENUM('PREPAID', 'COD') NOT NULL DEFAULT 'PREPAID',
  `cod_amount` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `shipping_fee` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `agent_id` BIGINT UNSIGNED NULL,
  `attempt_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `last_failure_reason` VARCHAR(1000) NULL,
  `proof_image_url` VARCHAR(1000) NULL,
  `assigned_at` DATETIME NULL,
  `delivered_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `shipments_tracking_unique` (`tracking_number`),
  UNIQUE KEY `shipments_order_reference_unique` (`order_reference`),
  KEY `shipments_status_created_idx` (`status`, `created_at`),
  KEY `shipments_agent_status_idx` (`agent_id`, `status`),
  CONSTRAINT `shipments_agent_fk` FOREIGN KEY (`agent_id`) REFERENCES `agents` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `delivery_attempts` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `shipment_id` BIGINT UNSIGNED NOT NULL,
  `attempt_number` INT UNSIGNED NOT NULL,
  `agent_id` BIGINT UNSIGNED NOT NULL,
  `result` ENUM('IN_PROGRESS', 'DELIVERED', 'FAILED') NOT NULL,
  `failure_reason` VARCHAR(1000) NULL,
  `started_at` DATETIME NOT NULL,
  `completed_at` DATETIME NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `delivery_attempt_number_unique` (`shipment_id`, `attempt_number`),
  CONSTRAINT `delivery_attempt_shipment_fk` FOREIGN KEY (`shipment_id`) REFERENCES `shipments` (`id`) ON DELETE CASCADE,
  CONSTRAINT `delivery_attempt_agent_fk` FOREIGN KEY (`agent_id`) REFERENCES `agents` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `shipment_events` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `shipment_id` BIGINT UNSIGNED NOT NULL,
  `from_status` VARCHAR(40) NULL,
  `to_status` VARCHAR(40) NOT NULL,
  `title` VARCHAR(160) NOT NULL,
  `note` VARCHAR(1000) NULL,
  `actor_type` ENUM('SYSTEM', 'ADMIN', 'SHIPPER') NOT NULL,
  `actor_id` BIGINT UNSIGNED NULL,
  `proof_image_url` VARCHAR(1000) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `shipment_events_timeline_idx` (`shipment_id`, `created_at`),
  CONSTRAINT `shipment_events_shipment_fk` FOREIGN KEY (`shipment_id`) REFERENCES `shipments` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
